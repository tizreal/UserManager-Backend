-- Baseline: the schema as it existed before Flyway was introduced, matching the
-- JPA mappings of User, Post, and Comment.
--
-- Fresh databases (local, tests, Docker) run this script. Existing databases are
-- baselined at version 1 instead (spring.flyway.baseline-on-migrate=true), so this
-- script is NOT executed against them; only V2 onward is applied.

CREATE TABLE users (
    user_id        integer GENERATED BY DEFAULT AS IDENTITY,
    first_name     varchar(255),
    last_name      varchar(255),
    user_name      varchar(255),
    password       varchar(255),
    phone_number   varchar(255),
    email          varchar(255),
    email_verified boolean,
    country_code   varchar(255),
    created_at     timestamp(6),
    updated_at     timestamp(6),
    PRIMARY KEY (user_id)
);

CREATE TABLE posts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    content     text NOT NULL,
    user_id     integer NOT NULL,
    likes_count integer DEFAULT 0,
    updated_at  timestamp(6),
    created_at  timestamp(6) NOT NULL,
    image       text,
    PRIMARY KEY (id),
    CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE comments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    content     text NOT NULL,
    post_id     bigint NOT NULL,
    user_id     integer NOT NULL,
    created_at  timestamp(6) NOT NULL,
    likes_count integer,
    updated_at  timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);
