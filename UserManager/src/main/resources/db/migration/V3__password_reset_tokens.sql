-- Single-use password-reset tokens.
--
-- Only the SHA-256 hash of each token is stored, so a database leak does not expose
-- usable reset links. A token is consumed with one conditional UPDATE
--   ... SET used_at = now() WHERE token_hash = ? AND used_at IS NULL AND expires_at > now()
-- which PostgreSQL serializes on the row: if two requests race, exactly one updates the
-- row and the other sees used_at already set and updates nothing.

CREATE TABLE password_reset_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     integer NOT NULL,
    token_hash  varchar(64) NOT NULL,
    expires_at  timestamp(6) with time zone NOT NULL,
    used_at     timestamp(6) with time zone,
    created_at  timestamp(6) with time zone NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ux_password_reset_tokens_hash UNIQUE (token_hash),
    -- Reset tokens are not user content; they go with the account.
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE INDEX ix_password_reset_tokens_user ON password_reset_tokens (user_id);
